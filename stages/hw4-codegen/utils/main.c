int read_int()
{
  int v;
  scanf("%d", &v);
  return v;
}

float read_fp()
{
  float v;
  scanf("%f", &v);
  return v;
}

void write_int(int v)
{
  printf("%d\n", v);
}

void write_fp(float v)
{
  printf("%f\n", v);
}

void write_str(char *str)
{
  printf("%s\n", str);
}

int main()
{
  __start_main();
  return 0;
}
